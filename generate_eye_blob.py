import struct
import numpy as np
import sys
import math

positions = []
orientations = []
focal_point_ws = []
diameters = []
ioas = []

max_position = np.array([-100000.0, -1000000.0, -1000000.0])
min_position = np.array([100000.0, 1000000.0, 1000000.0])

rescale = 0.001
facet_downscale = 0.001

# Get the input parameters
if(len(sys.argv) < 2):
    print("Error: Please supply a path to a CSV generated by the blender script.")
    exit()

input_path = sys.argv[1]


with open(input_path, "r") as f:
    for line in f:
        if line.startswith("#") or line.startswith("center_x"):
            continue
        data = line.split(",")
        position = [float(data[0]), float(data[1]), float(data[2])]
        position = [p*rescale for p in position]
        max_position = np.maximum(max_position, position)
        min_position = np.minimum(min_position, position)
        positions.append(position)
        orientations.append([float(data[3]), float(data[4]), float(data[5])])
        focal_point_ws.append(-float(data[7])*facet_downscale) # Gotta make it negative
        diameters.append(float(data[8])*2*rescale*facet_downscale) # Gotta times the radius by two.
        ioas.append(float(data[6])) # Store the angles

print(f"Max position: {max_position[0]:.16f}, {max_position[1]:.16f}, {max_position[2]:.16f}")
print(f"Min position: {min_position[0]:.16f}, {min_position[1]:.16f}, {min_position[2]:.16f}")
print(f"Average diameter: {np.asarray(diameters).mean():.16f}")
print(f"Average focal point distance: {np.asarray(focal_point_ws).mean():.16f}")
ioas = np.asarray([math.degrees(a) for a in ioas])
mean = ioas.mean()
std = ioas.std()
print(f"Min IO: {ioas.min():.1f}, max IO: {ioas.max():.1f}, mean IO: {mean:.1f}, standard deviation: {std:.1f}")
ioas1std = ioas[[abs(a-mean) <= std for a in ioas]]
print(f"[within 1 std] Min IO: {ioas1std.min():.1f}, max IO: {ioas1std.max():.1f}, mean IO: {ioas1std.mean():.1f} (outliers removed: {len(ioas)-len(ioas1std)})")
ioas2std = ioas[[abs(a-mean) <= std*2 for a in ioas]]
print(f"[within 2 std] Min IO: {ioas2std.min():.1f}, max IO: {ioas2std.max():.1f}, mean IO: {ioas2std.mean():.1f} (outliers removed: {len(ioas)-len(ioas2std)})")
print(f"Facet count: {len(positions)}")

with open(f"{input_path}.bin", "wb") as f:
    bytePos = 0
    for p in positions:
        for i in range(3):
            f.write(struct.pack('<f',p[i]))
            bytePos = bytePos + 4
    print(f"Byte pos after positions: {bytePos}")
    orientations_len = 0
    for o in orientations:
        for i in range(3):
            f.write(struct.pack('<f',o[i]))
            bytePos = bytePos + 4
            orientations_len = orientations_len + 4
    print(f"Byte pos after orientations: {bytePos}")
    print(f"Orientations len: {orientations_len}")
    focal_point_ws_len = 0
    for fw in focal_point_ws:
        f.write(struct.pack('<f',fw))
        bytePos = bytePos + 4
        focal_point_ws_len = focal_point_ws_len + 4
    print(f"Byte pos after focal point ws: {bytePos}")
    print(f"Focal point ws len: {focal_point_ws_len}")
    diameters_len = 0
    for d in diameters:
        f.write(struct.pack('<f',d))
        bytePos = bytePos + 4
        diameters_len = diameters_len + 4
    print(f"Byte pos after diameters: {bytePos}")
    print(f"Diameters len: {diameters_len}")
    print(f"Total byte pos: {bytePos}")
